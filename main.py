"""Точка входа: запуск программы «Система управления ТСЖ»."""

# tkinter - встроенная библиотека для окон
import tkinter as tk

# создание базы
from db import database

# наша библиотека элементов (кнопки, поля, шрифты)
from ui import kit

# главный класс программы
from ui.app import App


def main():
    """Создаёт базу данных (если её нет) и открывает главное окно."""
    # делаем окно чётким на экранах с масштабом 125%, 150%
    kit.enable_high_dpi()
    # подключаем шрифт Roboto из папки fonts
    kit.load_fonts()
    # создаём таблицы, если базы ещё нет
    database.init_db()
    # root - главное окно программы
    root = tk.Tk()
    # App сам выберет первый экран: регистрация председателя или вход
    App(root)
    # запускаем цикл окна: программа работает, пока окно не закрыто
    root.mainloop()


# этот блок выполняется только при запуске файла напрямую (python main.py)
if __name__ == "__main__":
    main()
